export function createTranslator(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return (key) => dict[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function formatAcresAndHa(ha, lang = "en") {
  const acres = (Number(ha) * 2.47105).toFixed(2);
  return lang === "te"
    ? `${acres} ఎకరాలు (${Number(ha).toFixed(2)} హె)`
    : `${acres} Acres (${Number(ha).toFixed(2)} ha)`;
}
